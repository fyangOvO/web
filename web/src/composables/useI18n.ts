/** 設置語言（同步到 localStorage） */
export function setLang(lang: SupportedLang) {
  currentLang.value = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch { /* ignore */ }
  // 同步到 html lang 屬性（SEO + 無障礙）
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang === 'zh-Hans' ? 'zh-CN' : lang === 'zh-Hant' ? 'zh-TW' : 'en';
  }
}

/** 從 localStorage / 瀏覽器語言 / 默認值恢復語言 */
export function initLang(): SupportedLang {
  const supported = new Set<SupportedLang>(['zh-Hant', 'zh-Hans', 'en']);
  // 1. localStorage
  try {
    const stored = localStorage.getItem(STORAGE_KEY) as SupportedLang | null;
    if (stored && supported.has(stored)) {
      currentLang.value = stored;
      return stored;
    }
  } catch { /* ignore */ }
  // 2. 瀏覽器語言
  if (typeof navigator !== 'undefined') {
    const browser = navigator.language;
    if (browser.startsWith('zh')) {
      // zh-TW / zh-HK / zh-MO → 繁體；其他 zh → 簡體
      const isTrad = ['zh-TW', 'zh-HK', 'zh-MO'].some((l) => browser === l || browser.startsWith(l));
      const resolved: SupportedLang = isTrad ? 'zh-Hant' : 'zh-Hans';
      currentLang.value = resolved;
      return resolved;
    }
    if (browser.startsWith('en')) {
      currentLang.value = 'en';
      return 'en';
    }
  }
  // 3. 默認繁體
  currentLang.value = 'zh-Hant';
  return 'zh-Hant';
}

/** 翻譯函數 */
export function t(key: TranslationKey): string {
  const map = messages[currentLang.value === 'zh-Hant' ? 'zhHant' : currentLang.value === 'zh-Hans' ? 'zhHans' : 'en'];
  return map[key] ?? key;
}

/** 帶插值的翻譯（{n} 占位符） */
export function tFmt(key: TranslationKey, vars: Record<string, string | number>): string {
  let s = t(key);
  for (const [k, v] of Object.entries(vars)) {
    s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return s;
}

/** Vue composable：返回響應式翻譯函數 */
export function useI18n() {
  const lang = computed(() => currentLang.value);
  const $t = (key: TranslationKey) => t(key);
  const $tFmt = (key: TranslationKey, vars: Record<string, string | number>) => tFmt(key, vars);
  return { lang, $t, $tFmt, setLang, LANG_META };
}

